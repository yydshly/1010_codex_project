#!/usr/bin/env node
/**
 * Generates docs/PROVENANCE.md from the provenance blocks of every catalog asset.
 * Requires the dev server (npm run dev, port 5199); reads the harness list mode
 * (harness.html?list=1 -> window.__defs) in headless Chrome/Edge.
 *
 *   node scripts/provenance.mjs [--base http://127.0.0.1:5198] [--out docs/PROVENANCE.md]
 */
import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const outArg = args.indexOf('--out');
const OUT = path.resolve(outArg >= 0 ? args[outArg + 1] : 'docs/PROVENANCE.md');
const baseArg = args.indexOf('--base');
const BASE = baseArg >= 0 ? args[baseArg + 1] : 'http://127.0.0.1:5199';

const executablePath = [
  process.env.BROWSER_PATH,
  path.join(process.env.LOCALAPPDATA ?? '', 'Google/Chrome/Application/chrome.exe'),
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
].filter(Boolean).find((p) => fs.existsSync(p));
if (!executablePath) {
  console.error('No Chrome/Edge executable found. Set BROWSER_PATH.');
  process.exit(2);
}

const browser = await puppeteer.launch({ executablePath, headless: true, args: ['--no-first-run'] });
let defs;
try {
  const page = await browser.newPage();
  await page.goto(`${BASE}/harness.html?list=1`, { waitUntil: 'load', timeout: 120000 });
  await page.waitForFunction('window.__ready === true', { timeout: 180000 });
  defs = await page.evaluate(() => window.__defs);
} finally {
  await browser.close();
}

const factionName = (d) => d.factionName ?? d.faction;
const CATEGORY_ORDER = ['Infantry', 'Weapons', 'Equipment', 'Vehicles', 'Armor', 'Artillery', 'Aircraft'];
const listed = defs.filter((d) => !d.hidden);
listed.sort((a, b) =>
  a.faction.localeCompare(b.faction) ||
  CATEGORY_ORDER.indexOf(a.category) - CATEGORY_ORDER.indexOf(b.category) ||
  a.name.localeCompare(b.name));

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const lines = [];
lines.push('# Asset Provenance Record');
lines.push('');
lines.push('Generated by `node scripts/provenance.mjs` from the `provenance` block of every catalog entry');
lines.push('(`src/assets/**/*.asset.ts`). Do not edit by hand - edit the asset and regenerate.');
lines.push('');
lines.push('Every model in this project is procedurally modelled in TypeScript for this project: no external');
lines.push('meshes, scans or texture images are used. Textures are generated in code at runtime. The references');
lines.push('below are the public sources consulted for dimensions, details and historical facts.');
lines.push('');
lines.push(`Catalog entries: ${listed.length} (${listed.filter((d) => d.status === 'available').length} available, ` +
  `${listed.filter((d) => d.status !== 'available').length} marked unavailable).`);
lines.push('');
lines.push('| Entry | Country | Category | Status |');
lines.push('|---|---|---|---|');
for (const d of listed) {
  lines.push(`| ${esc(d.name)} (\`${d.id}\`) | ${factionName(d)} | ${d.category} | ${d.status} |`);
}
lines.push('');
for (const d of listed) {
  const p = d.provenance ?? {};
  lines.push(`## ${d.name} - ${factionName(d)}, ${d.category}`);
  lines.push('');
  lines.push(`- Id: \`${d.id}\` (source: \`src/assets/${d.path}.asset.ts\`)`);
  lines.push(`- Status: ${d.status}${d.status !== 'available' && d.unavailableReason ? ` - ${d.unavailableReason}` : ''}`);
  lines.push(`- Method: ${esc(p.method)}`);
  lines.push(`- Author: ${esc(p.author)}`);
  lines.push(`- License: ${esc(p.license)}`);
  lines.push(`- Textures: ${esc(p.textures)}`);
  if (p.notes) lines.push(`- Notes: ${esc(p.notes)}`);
  const refs = (p.references ?? []).filter(Boolean);
  if (refs.length) {
    lines.push('- References:');
    for (const r of refs) lines.push(`  - ${esc(r)}`);
  } else {
    lines.push('- References: none recorded');
  }
  lines.push('');
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`${OUT}: ${listed.length} entries`);
