import fs from 'node:fs/promises';
import path from 'node:path';
import {parseArgs} from 'node:util';
import puppeteer from 'puppeteer-core';
import {web,project} from './build-research.mjs';
const{values}=parseArgs({options:{url:{type:'string'},live:{type:'boolean',default:false}}});
const url=values.url||'http://127.0.0.1:5198/1010_codex_project/008-pdoom-video/research.html';
const executablePath=process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe';
const browser=await puppeteer.launch({executablePath,headless:true,args:['--no-sandbox','--disable-gpu','--disable-dev-shm-usage']});
const page=await browser.newPage(),errors=[],failures=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400)failures.push({status:r.status(),url:r.url()})});
const assert=(v,name)=>{checks.push({name,passed:!!v});if(!v)throw Error(name+' 未通过')};
const suffix=values.live?'live':'local';
try{
 await page.setViewport({width:1440,height:1000,deviceScaleFactor:1});
 await page.goto(url,{waitUntil:'domcontentloaded',timeout:60000});
 assert((await page.$$eval('.summary-section',n=>n.length))===9,'九主题摘要');
 assert((await page.$$eval('.summary-section p',n=>n.length))===37,'37 段正文完整');
 assert((await page.$$eval('.module',n=>n.length))===9,'九组模块');
 assert((await page.$$eval('.document',n=>n.length))===21,'21 份资料入口');
 const heights=await page.evaluate(()=>({page:document.documentElement.scrollHeight,viewport:window.innerHeight}));
 assert(heights.page>heights.viewport*4,'完整研究正文已呈现');
 for(const v of ['#video15','#video30']){
  await page.waitForFunction(selector=>{const video=document.querySelector(selector);return video.readyState>=1&&video.duration>0}, {timeout:30000},v);
  const before=await page.$eval(v,n=>({duration:n.duration,width:n.videoWidth,height:n.videoHeight}));
  assert(Math.abs(before.duration-(v==='#video15'?15:30))<.1,v+' 元数据');
  await page.$eval(v,n=>{n.muted=true;return n.play()});
  await page.waitForFunction(selector=>document.querySelector(selector).currentTime>.25,{timeout:15000},v);
  await page.$eval(v,n=>n.pause());assert(true,v+' 实际播放');
 }
 await page.click('[data-step="2"]');assert((await page.$eval('#stepTitle',n=>n.textContent))==='分镜规划','执行链交互');
 await page.click('[data-style="1"]');await page.waitForFunction(()=>document.querySelector('#styleImage').complete);
 assert((await page.$eval('#styleImage',n=>n.src)).includes('mv-style-ink.png'),'实际素描画风切换');
 await page.click('[data-style="2"]');await page.waitForFunction(()=>document.querySelector('#styleImage').complete);
 assert((await page.$eval('#styleImage',n=>n.src)).includes('mv-style-flat.png'),'实际平涂画风切换');
 await page.click('[data-doc="./web/THIRD_PARTY_NOTICES.md"]');
 await page.waitForFunction(()=>document.querySelector('#documentText').textContent.includes('Permission is hereby granted'));
 assert(true,'完整 MIT 原文页内阅读');
 await page.keyboard.press('Escape');assert(!(await page.$eval('#documentDialog',n=>n.open)),'资料弹窗 Escape 关闭');
 await page.type('#researchSearch','口型');
 assert((await page.$$eval('.summary-section:not([hidden])',n=>n.length))>0,'中文摘要检索');
 await page.click('#clearSearch');assert((await page.$$eval('.summary-section:not([hidden])',n=>n.length))===9,'清除检索恢复完整摘要');
 await page.click('[data-filter="验证"]');assert((await page.$$eval('.document:not([hidden])',n=>n.every(x=>x.dataset.group==='验证'))),'资料分类');
 await page.click('[data-filter="全部"]');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.click('[data-poster]');
 assert(await page.$eval('#posterDialog',n=>n.open),'引导图放大');
 const before=await page.$eval('#posterFull',n=>parseInt(n.style.width));await page.click('#zoomIn');
 assert((await page.$eval('#posterFull',n=>parseInt(n.style.width)))>before,'总览图缩放');
 await page.keyboard.press('Escape');
 await page.click('[data-step="0"]');await page.click('[data-style="0"]');
 await page.evaluate(()=>window.scrollTo(0,0));
 const imagePath=path.join(project,'assets/research-'+suffix+'-desktop.png');
 await page.screenshot({path:imagePath});
 await page.setViewport({width:390,height:844,deviceScaleFactor:1});
 await page.goto(url,{waitUntil:'domcontentloaded',timeout:60000});
 // Scroll through sections to load lazy assets, then measure the actual page.
 await page.evaluate(async()=>{for(let y=0;y<document.documentElement.scrollHeight;y+=650){window.scrollTo({top:y,behavior:'instant'});await new Promise(r=>setTimeout(r,60))}window.scrollTo({top:0,behavior:'instant'})});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'390px 窄屏无横向溢出');
 await page.waitForFunction(()=>[...document.querySelectorAll('img')].every(x=>x.complete&&x.naturalWidth),{timeout:30000});
 const unloaded=await page.$$eval('img',n=>n.filter(x=>!x.complete||!x.naturalWidth).map(x=>x.src));
 assert(unloaded.length===0,'全部图片加载');
 const mobilePath=path.join(project,'assets/research-'+suffix+'-mobile.png');
 await page.screenshot({path:mobilePath});
 if(errors.length||failures.length)console.error(JSON.stringify({errors,failures},null,2));
 assert(errors.length===0,'浏览器无运行错误');assert(failures.length===0,'页面资源无 HTTP 失败');
 const report={date:'2026-10-12',checkedAt:new Date().toISOString(),url,mode:values.live?'线上':'本地 Pages 路径预览',browser:await browser.version(),viewportChecks:[1440,390],checks,errors,failures,screenshots:[path.relative(project,imagePath).replaceAll('\\','/'),path.relative(project,mobilePath).replaceAll('\\','/')]};
 await fs.writeFile(path.join(project,'notes/research-'+suffix+'-verification.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify({passed:checks.length,errors,failures,screenshots:report.screenshots},null,2));
}finally{await browser.close()}
